sap.ui.define([
    "sap/ui/core/mvc/Controller",
    "sap/ui/model/json/JSONModel",
    "sap/m/MessageToast",
    "sap/m/MessageBox"
], function (Controller, JSONModel, MessageToast, MessageBox) {
    "use strict";

    return Controller.extend("smartprocurex.controller.CreateRequest", {

        onInit: function () {
            // Form data model
            var oCreateModel = new JSONModel({
                requestedBy_ID: "",
                department_ID: "",
                priority: "",
                totalAmount: "",
                justification: ""
            });
            this.getView().setModel(oCreateModel, "createModel");

            // Load Users and Departments from Identity service
            this._loadUsers();
            this._loadDepartments();
        },

        /**
         * Fetches all Users from the Identity service and sets them on a JSONModel.
         */
        _loadUsers: async function () {
            try {
                var response = await fetch("/odata/v4/identity/Users");
                var data = await response.json();
                this.getView().setModel(new JSONModel(data), "usersModel");
            } catch (error) {
                MessageBox.error("Failed to load users: " + error.message);
            }
        },

        /**
         * Fetches all Departments from the Identity service and sets them on a JSONModel.
         */
        _loadDepartments: async function () {
            try {
                var response = await fetch("/odata/v4/identity/Departments");
                var data = await response.json();
                this.getView().setModel(new JSONModel(data), "departmentsModel");
            } catch (error) {
                MessageBox.error("Failed to load departments: " + error.message);
            }
        },

        /**
         * Resets the form model to blank values.
         */
        _resetForm: function () {
            this.getView().getModel("createModel").setData({
                requestedBy_ID: "",
                department_ID: "",
                priority: "",
                totalAmount: "",
                justification: ""
            });
        },

        /**
         * Validates required fields and returns true if all are filled.
         */
        _validateForm: function () {
            var oData = this.getView().getModel("createModel").getData();
            var aErrors = [];

            if (!oData.requestedBy_ID) {
                aErrors.push("Requested By is required.");
            }
            if (!oData.department_ID) {
                aErrors.push("Department is required.");
            }
            if (!oData.priority) {
                aErrors.push("Priority is required.");
            }
            if (!oData.totalAmount || isNaN(parseFloat(oData.totalAmount)) || parseFloat(oData.totalAmount) <= 0) {
                aErrors.push("Total Amount must be a positive number.");
            }

            if (aErrors.length > 0) {
                MessageBox.error(aErrors.join("\n"));
                return false;
            }

            return true;
        },

        /**
         * Saves the new Purchase Request via POST to the OData service.
         * Note: requestNumber, requestDate, and status are auto-generated by the backend.
         */
        onSave: async function () {
            if (!this._validateForm()) {
                return;
            }

            var oData = this.getView().getModel("createModel").getData();

            var oPayload = {
                requestedBy_ID: oData.requestedBy_ID,
                department_ID: oData.department_ID,
                priority: oData.priority,
                totalAmount: parseFloat(oData.totalAmount),
                justification: oData.justification ? oData.justification.trim() : ""
            };

            try {
                var response = await fetch("/odata/v4/procurement/PurchaseRequests", {
                    method: "POST",
                    headers: {
                        "Content-Type": "application/json"
                    },
                    body: JSON.stringify(oPayload)
                });

                if (response.ok) {
                    MessageToast.show("Purchase Request created successfully.");
                    this._resetForm();
                    this.getOwnerComponent().getRouter().navTo("RouteMainView");
                } else {
                    var errorData = await response.json();
                    MessageBox.error(
                        errorData.error?.message || "Failed to create Purchase Request."
                    );
                }
            } catch (error) {
                MessageBox.error(error.message);
            }
        },

        /**
         * Navigates back to the Dashboard without saving.
         */
        onCancel: function () {
            this._resetForm();
            this.getOwnerComponent().getRouter().navTo("RouteMainView");
        }

    });
});
